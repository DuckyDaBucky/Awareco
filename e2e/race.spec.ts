import { expect, test } from '@playwright/test'

test('historical replay stays synchronized through playback, switching, seeking and restart', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  // The loaded app must not need any external service, including fonts.
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    return ['127.0.0.1', 'localhost'].includes(url.hostname) ? route.continue() : route.abort()
  })
  await page.clock.install({ time: new Date('2026-10-21T19:00:00Z') })
  await page.clock.pauseAt(new Date('2026-10-21T19:00:01Z'))
  await page.goto('/')
  await page.getByRole('link', { name: 'Race weekend', exact: true }).click()
  const dashboard = page.getByTestId('race-dashboard')
  await expect(dashboard).toBeVisible()
  await expect(page.getByTestId('race-time')).toHaveText('00:00:00')
  await expect(page.getByRole('button', { name: '20×', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Play replay', exact: true }).click()
  const initialPosition = await page.getByTestId('selected-car').getAttribute('transform')
  await page.clock.runFor(1000)
  const firstTime = Number(await dashboard.getAttribute('data-time'))
  expect(firstTime).toBeGreaterThan(19)
  expect(firstTime).toBeLessThan(21)
  expect(await page.getByTestId('selected-car').getAttribute('transform')).not.toBe(initialPosition)
  expect(Number(await page.getByTestId('fuel-value').innerText())).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Pause replay', exact: true }).click()
  const frozen = await dashboard.getAttribute('data-time')
  const frozenFuel = await page.getByTestId('fuel-value').innerText()
  const frozenCar = await page.getByTestId('selected-car').getAttribute('transform')
  const frozenEnergy = await page.locator('.race-energy-values').innerText()
  const frozenInsight = await page.getByTestId('impact-insight').innerText()
  await page.clock.runFor(3000)
  expect(await dashboard.getAttribute('data-time')).toBe(frozen)
  expect(await page.getByTestId('fuel-value').innerText()).toBe(frozenFuel)
  expect(await page.getByTestId('selected-car').getAttribute('transform')).toBe(frozenCar)
  expect(await page.locator('.race-energy-values').innerText()).toBe(frozenEnergy)
  expect(await page.getByTestId('impact-insight').innerText()).toBe(frozenInsight)
  await page.getByRole('button', { name: '60×', exact: true }).click()
  await page.getByRole('button', { name: 'Play replay', exact: true }).click()
  await page.clock.runFor(1000)
  // At 60× one 60 Hz animation frame spans up to one replay second.
  const resumedDelta = Number(await dashboard.getAttribute('data-time')) - firstTime
  expect(resumedDelta).toBeGreaterThan(58.5)
  expect(resumedDelta).toBeLessThan(61.5)
  await page.getByRole('button', { name: 'Pause replay', exact: true }).click()
  const switchTime = await dashboard.getAttribute('data-time')
  await page.getByRole('button', { name: '18 STROLL SWITCH DRIVER' }).click()
  expect(await dashboard.getAttribute('data-time')).toBe(switchTime)
  await expect(page.getByRole('button', { name: '18 STROLL SELECTED DRIVER' })).toHaveAttribute('aria-pressed', 'true')
  const slider = page.getByRole('slider', { name: 'Race timeline' })
  await slider.press('End')
  await expect(page.getByTestId('fuel-value')).toHaveText('100.0')
  await expect(page.getByTestId('carbon-value')).toHaveText('397.0')
  await expect(page.getByTestId('lap-counter')).toContainText('56')
  await slider.press('Home')
  await expect(page.getByTestId('fuel-value')).toHaveText('0.0')
  await expect(page.getByTestId('race-time')).toHaveText('00:00:00')
  // Seek into the race with a real range-input interaction, then save the desktop view.
  const bounds = await slider.boundingBox()
  expect(bounds).not.toBeNull()
  await slider.click({ position: { x: bounds!.width * .43, y: bounds!.height / 2 } })
  const seekTime = Number(await dashboard.getAttribute('data-time'))
  expect(seekTime).toBeGreaterThan(2000)
  const seekFuel = await page.getByTestId('fuel-value').innerText()
  await expect(page.getByTestId('lap-counter')).not.toContainText('01 /')
  await page.screenshot({ path: 'test-results/race-desktop.png', fullPage: true })
  await slider.press('End')
  await slider.click({ position: { x: bounds!.width * .43, y: bounds!.height / 2 } })
  expect(await page.getByTestId('fuel-value').innerText()).toBe(seekFuel)
  await page.getByText('How this simulation works', { exact: false }).click()
  await expect(page.getByRole('heading', { name: '03 / Estimated fuel & carbon' })).toBeVisible()
  await page.getByRole('button', { name: 'Restart', exact: true }).click()
  await expect(page.getByTestId('fuel-value')).toHaveText('0.0')
  await expect(dashboard).toHaveAttribute('data-playing', 'false')
  await page.getByText('How this simulation works', { exact: false }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/race-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('playback stops at the race finish and play again starts a fresh synchronized replay', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-21T19:00:00Z') })
  await page.clock.pauseAt(new Date('2026-10-21T19:00:01Z'))
  await page.goto('/race')
  const dashboard = page.getByTestId('race-dashboard')
  await expect(dashboard).toBeVisible()
  await page.getByRole('slider', { name: 'Race timeline' }).press('End')
  await page.getByRole('slider', { name: 'Race timeline' }).press('ArrowLeft')
  await page.getByRole('button', { name: 'Play replay', exact: true }).click()
  await page.clock.runFor(1000)
  await expect(dashboard).toHaveAttribute('data-playing', 'false')
  await expect(dashboard).toHaveAttribute('data-time', '5714.939')
  await expect(page.getByTestId('fuel-value')).toHaveText('100.0')
  await page.getByRole('button', { name: 'Play replay', exact: true }).click()
  await expect(dashboard).toHaveAttribute('data-time', '0.000')
  await expect(page.getByTestId('fuel-value')).toHaveText('0.0')
  await page.clock.runFor(1000)
  expect(Number(await dashboard.getAttribute('data-time'))).toBeGreaterThan(19)
})
